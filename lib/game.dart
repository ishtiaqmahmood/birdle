/// Game logic and supporting types for Birdle,
/// a five-letter word-guessing game similar to Wordle.
///
/// Defines the [Game] state machine and the
/// [Word], [Letter], and [HitType] data model used to
/// represent guesses and their evaluation against a hidden word.
///
/// ## Features
/// - Deterministic or random word selection
/// - Configurable maximum guesses
/// - Complete game state tracking (wins, losses, streaks)
/// - Guess evaluation with hit, partial, and miss feedback
///
/// ## Example
/// ```dart
/// final game = Game(seed: 42); // Deterministic word
/// final result = game.guess('aback');
/// if (game.didWin) {
///   print('Congratulations!');
/// }
/// ```
library;

import 'dart:collection';
import 'dart:math';

/// The result of evaluating a [Letter] of a guess against the hidden word.
///
/// Used to provide visual feedback in the UI about how each letter
/// in a guess compares to the hidden word.
enum HitType {
  /// The letter hasn't yet been evaluated.
  none,

  /// The letter matches the hidden word's letter at the same position.
  /// Displayed with green color in the UI.
  hit,

  /// The letter is in the hidden word, but at a different position.
  /// Displayed with yellow/amber color in the UI.
  partial,

  /// The letter doesn't appear in the hidden word.
  /// Displayed with gray color in the UI.
  miss,
}

/// A single character paired with its [HitType] against the hidden word.
///
/// Uses a record type to immutably pair a character with its evaluation result.
typedef Letter = ({String char, HitType type});

